const fs = require("node:fs");
const path = require("node:path");

function formatCalVer(date = new Date()) {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, "0");
  const day = String(date.getDate()).padStart(2, "0");
  const hour = String(date.getHours()).padStart(2, "0");
  return `${year}.${month}.${day}.${hour}`;
}

const calver = formatCalVer();
const outputPath = path.resolve(__dirname, "..", "electron", "generated-build-info.ts");
const fileContent = `// Auto-generated by scripts/write-build-calver.cjs at build time.\nexport const BUILD_CALVER = "${calver}";\n`;

fs.writeFileSync(outputPath, fileContent, "utf8");
console.log(`[build:calver] BUILD_CALVER=${calver}`);
